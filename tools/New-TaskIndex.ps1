# Regenerates docs/tasks/README.md from the task records.
# Usage: powershell -NoProfile -ExecutionPolicy Bypass -File tools/New-TaskIndex.ps1
$ErrorActionPreference = 'Stop'
$repo = Split-Path -Parent $PSScriptRoot
$tasksDir = Join-Path $repo 'docs/tasks'
$outPath = Join-Path $tasksDir 'README.md'

function Get-VerdictText([string[]]$lines) {
    for ($i = 0; $i -lt $lines.Count; $i++) {
        if ($lines[$i] -match '^\**Verdict\b') {
            return (($lines[$i] -replace '^\**Verdict\b\**:?\**\s*', '') -replace '\*\*', '').Trim()
        }
        if ($lines[$i] -match '^#+\s*Verdict') {
            for ($j = $i + 1; $j -lt $lines.Count; $j++) {
                if ($lines[$j].Trim() -ne '' -and $lines[$j] -notmatch '^#') {
                    return ($lines[$j] -replace '\*\*', '').Trim()
                }
            }
        }
    }
    return ''
}

function Get-VerdictSummary([string[]]$lines) {
    $text = Get-VerdictText $lines
    if (-not $text) { return 'No verdict recorded; read the record.' }
    $sentences = @([regex]::Matches($text, '[^.]*\.(?=\s|$)') | ForEach-Object { $_.Value.Trim() })
    $summary = if ($sentences.Count -gt 0) { ($sentences | Select-Object -First 2) -join ' ' } else { $text }
    if ($summary.Length -gt 220) { $summary = $summary.Substring(0, 217) + '...' }
    return $summary -replace '\|', '\|'
}

$rows = foreach ($file in Get-ChildItem -LiteralPath $tasksDir -Filter 'T*.md' | Sort-Object Name) {
    $lines = @(Get-Content -LiteralPath $file.FullName -Encoding UTF8)
    $heading = $lines | Where-Object { $_ -like '# *' } | Select-Object -First 1
    if ($heading -notmatch '^# (T\w+) \S (.+)$') { throw "Unexpected heading in $($file.Name)" }
    $id = $Matches[1]
    $title = ($Matches[2] -replace '\|', '\|')
    "| [$id]($($file.Name)) | $title | $(Get-VerdictSummary $lines) |"
}

$content = @(
    '# Task index'
    ''
    'Generated by `tools/New-TaskIndex.ps1` from the records in this folder. Do not edit by hand; rerun the script after changing a record.'
    ''
    'The verdict column quotes the first sentences of each record''s `Verdict` line. Gate and owner are stated in each record''s opening paragraph, because the records do not share a label for them.'
    ''
    'Records through T128 retain historical commands and paths. See [the folder guide](../folder-guide.md#names-used-by-older-records) for current equivalents.'
    ''
    '| ID | Title | Verdict |'
    '|---|---|---|'
) + $rows

[IO.File]::WriteAllText($outPath, (($content -join "`n") + "`n"), [Text.UTF8Encoding]::new($false))
Write-Output "Wrote $($rows.Count) rows to $outPath"
