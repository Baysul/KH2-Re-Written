//! Native script trap table: slot, public label, argument count and result flag.
//! Flags are the executable's own table words (low 16 bits = arguments popped, bit 30 = a
//! value is pushed); the labels are OpenKH's and are names only, not behavior evidence.

/// One trap slot.
#[derive(Clone, Copy, Debug, PartialEq, Eq)]
pub struct Trap {
    pub table: u16,
    pub index: u16,
    pub flags: u32,
    pub name: &'static str,
}

impl Trap {
    pub const fn arguments(&self) -> usize {
        (self.flags & 0xffff) as usize
    }
    pub const fn returns(&self) -> bool {
        self.flags & 0x4000_0000 != 0
    }
}

pub fn lookup(table: u16, index: u16) -> Option<&'static Trap> {
    TRAPS
        .binary_search_by_key(&(table, index), |t| (t.table, t.index))
        .ok()
        .map(|i| &TRAPS[i])
}

